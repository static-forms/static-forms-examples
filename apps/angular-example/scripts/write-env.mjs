// Angular has no built-in support for environment variables, so this script
// writes NG_APP_STATICFORMS_API_KEY (from the shell or a local .env file)
// into a generated TypeScript module before `ng serve` / `ng build`.
import { existsSync, writeFileSync } from 'node:fs';

if (existsSync('.env')) process.loadEnvFile('.env');

const apiKey = process.env.NG_APP_STATICFORMS_API_KEY || 'YOUR_API_KEY';

writeFileSync(
  'src/env.generated.ts',
  `// Generated by scripts/write-env.mjs. Do not edit.\nexport const STATICFORMS_API_KEY = ${JSON.stringify(apiKey)};\n`,
);
